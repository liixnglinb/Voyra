export function buildSpecMarkdown(productId = 'all') {
  const products = productId === 'all' ? SOFTWARE_SPECS : SOFTWARE_SPECS.filter((p) => p.id === productId);
  const text = ['# Voyra 软件 UI 规范', '', '版本：1.0 · 2026-10-02', '', '这是目标设计与验收契约，不代表所有业务交互已实现；预览不是实时数据。', '', '## 平台通用规范'];
  for (const section of UI_SECTIONS) {
    text.push('', `### ${section.title}`);
    for (const r of COMMON_RULES[section.id]) text.push('', `#### ${r.name}`, r.rule, `验收：${r.check}`);
  }
  for (const p of products) {
    text.push('', `## ${p.name} · ${p.en}`, '', `核心任务：${p.task}`, `平台：${p.platform}`, `导航：${p.nav.join(' → ')}`);
    for (const section of UI_SECTIONS) {
      text.push('', `### ${section.title}`);
      for (const r of p.rules[section.id]) text.push('', `#### ${r.name}`, r.rule, `验收：${r.check}`);
    }
    text.push('', '### 重点验收场景', ...p.acceptance.map((x) => `- ${x}`));
  }
  text.push('', '## 组件状态矩阵', '', '| 组件 | 默认 | 悬停 | 按压 | 焦点 | 加载 | 禁用 | 成功 | 失败 |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- |', ...STATE_MATRIX.map((r) => `| ${r.join(' | ')} |`), '');
  return text.join('\n');
}
