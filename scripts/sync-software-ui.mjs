import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';

// Explicit roots only; never scans the user's desktop or credentials.
// Token Monitor 自 v1.9.13 起退出共用 UI（自带 webapp/static/styles/tokens.css 单一源），
// 不再由本脚本同步；传 token=... 会明确报 Unknown product，而不是静默生成副本。
const workspace = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const targets = { chronicle:'src/styles', disk:'src/styles', checkin:'src/server', jacquard:'static' };
const write = process.argv.includes('--write');
const roots = process.argv.slice(2).filter((x) => x.includes('=')).map((x) => { const at=x.indexOf('='); return [x.slice(0,at),x.slice(at+1)]; });
if (!roots.length) throw new Error('Pass explicit id=absolute-directory arguments; use --write to sync.');
const foundation = await readFile(resolve(workspace,'public/design-system/voyra-foundation.css'),'utf8');
const base = await readFile(resolve(workspace,'design-system/software-base.css'),'utf8');
const dialogs = await readFile(resolve(workspace,'design-system/legacy-dialogs.js'),'utf8');
const stripImports = (css) => css.replace(/^@import[^;]+;\s*/gm,'');
for (const [id,root] of roots) {
  if (!targets[id]) throw new Error(`Unknown product: ${id}`);
  if (!/^(?:[A-Za-z]:[\\/]|\/)/.test(root)) throw new Error('Absolute roots required.');
  const adapter = await readFile(resolve(workspace,`design-system/adapters/${id}.css`),'utf8');
  const destination = resolve(root,targets[id]);
  const files = id === 'checkin'
    ? [['voyra-ui.ts', `// Generated by Voyra scripts/sync-software-ui.mjs. Do not edit by hand.\nexport const VOYRA_UI_CSS = ${JSON.stringify(`${foundation}\n${stripImports(base)}\n${stripImports(adapter)}`)}\n`]]
    : [['voyra-foundation.css',foundation],['voyra-software-base.css',base],['voyra-ui.css',adapter]];
  if (id === 'jacquard') {
    files.push(['voyra-dialogs.js',dialogs]);
    files.push(['voyra-ui.js',await readFile(resolve(workspace,'design-system/adapters/jacquard-ui.js'),'utf8')]);
  }
  if (id === 'checkin') files[0][1] += 'export const VOYRA_UI_JS = ' + JSON.stringify(dialogs) + '\n';
  if (id === 'chronicle') {
    // The product's release gate requires Prettier formatting, including generated CSS.
    const prettier = createRequire(resolve(root,'package.json'))('prettier');
    const settings = await prettier.resolveConfig(resolve(destination,'voyra-ui.css'));
    for (const file of files) file[1] = await prettier.format(file[1], { ...settings, parser:'css' });
  }
  for (const [name,content] of files) {
    const path=resolve(destination,name);
    if (write) { await mkdir(destination,{recursive:true}); await writeFile(path,content,'utf8'); }
    const actual=await readFile(path,'utf8').catch(() => '');
    const equal=actual===content;
    console.log(`${id} / ${name}: ${equal ? 'OK' : 'DRIFT'} ${createHash('sha256').update(content).digest('hex').slice(0,12)}`);
    if (!equal) process.exitCode=1;
  }
}
